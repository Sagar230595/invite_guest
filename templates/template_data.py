def get_template_by_id(template_id: str) -> dict:
    """Retrieves a template by its unique ID, defaulting to royal_wedding."""
    for t in TEMPLATES:
        if t["id"] == template_id:
            return t
    return TEMPLATES[0]


def get_all_categories() -> list:
    """Returns sorted list of unique template categories."""
    categories = sorted(list(set(t["category"] for t in TEMPLATES)))
    return ["All Categories"] + categories
